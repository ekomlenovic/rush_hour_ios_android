import {
  addSample,
  defaultLevelMs,
  estimateLevelMs,
  LONG_LEVEL_MS,
  MAX_SAMPLES,
  needsConfirmation,
  sampleKey,
  speedFactor,
  type GenerationSamples,
} from '../utils/generationEstimate';

/** The measures of a phone that generated these levels, in this order */
const measured = (...levels: [string, number, number][]): GenerationSamples =>
  levels.reduce((samples, [difficulty, size, ms]) => addSample(samples, difficulty, size, ms), {} as GenerationSamples);

describe('map generator estimate (issue 162)', () => {
  it('depends on the grid size, not only on the difficulty', () => {
    expect(estimateLevelMs('NORMAL', 8, {})).toBeGreaterThan(estimateLevelMs('NORMAL', 7, {}));
    expect(estimateLevelMs('NORMAL', 7, {})).toBeGreaterThan(estimateLevelMs('NORMAL', 6, {}));
    expect(estimateLevelMs('HARD', 8, {})).toBeGreaterThan(estimateLevelMs('HARD', 6, {}));
  });

  it('asks a confirmation for the combinations that freeze the app a minute or more, not for the others', () => {
    for (const [difficulty, size] of [['NORMAL', 8], ['HARD', 7], ['HARD', 8], ['EXPERT', 6], ['MASTER', 7]] as const) {
      expect([difficulty, size, needsConfirmation(difficulty, size, {})]).toEqual([difficulty, size, true]);
    }
    for (const [difficulty, size] of [['EASY', 6], ['EASY', 8], ['NORMAL', 6], ['NORMAL', 7], ['HARD', 6]] as const) {
      expect([difficulty, size, needsConfirmation(difficulty, size, {})]).toEqual([difficulty, size, false]);
    }
  });

  it('follows the times measured on the phone for a combination already generated', () => {
    // Easy as fast as the table, Normal 6x6 measured at 8 s three times
    const samples = measured(
      ['EASY', 6, defaultLevelMs('EASY', 6)], ['EASY', 6, defaultLevelMs('EASY', 6)], ['EASY', 6, defaultLevelMs('EASY', 6)],
      ['NORMAL', 6, 8000], ['NORMAL', 6, 8000], ['NORMAL', 6, 8000],
    );
    const estimate = estimateLevelMs('NORMAL', 6, samples);
    // Three measures against the table counted as one: close to the measures, above the table
    expect(estimate).toBeGreaterThan(5000);
    expect(estimate).toBeLessThan(8000);
    // Measured alone, the phone's speed brings the table to the measures too
    expect(estimateLevelMs('NORMAL', 6, measured(['NORMAL', 6, 8000]))).toBeCloseTo(8000);
  });

  it('scales the combinations never generated by the speed of the phone on the others', () => {
    const slowPhone = measured(['EASY', 6, defaultLevelMs('EASY', 6) * 4], ['EASY', 6, defaultLevelMs('EASY', 6) * 4]);
    expect(speedFactor(slowPhone)).toBeCloseTo(4);
    expect(estimateLevelMs('HARD', 7, slowPhone)).toBeCloseTo(defaultLevelMs('HARD', 7) * 4);
    // Three times faster than the table: Hard 7x7 well under a minute, no confirmation any more
    const fastPhone = measured(['NORMAL', 6, defaultLevelMs('NORMAL', 6) / 3]);
    expect(estimateLevelMs('HARD', 7, fastPhone)).toBeLessThan(LONG_LEVEL_MS / 2);
    expect(needsConfirmation('HARD', 7, fastPhone)).toBe(false);
  });

  it('still confirms a combination that once took over a minute, even if it is fast on average', () => {
    const samples = measured(['NORMAL', 7, 70_000], ...Array.from({ length: 19 }, () => ['NORMAL', 7, 2000] as [string, number, number]));
    expect(estimateLevelMs('NORMAL', 7, samples)).toBeLessThan(LONG_LEVEL_MS / 4);
    expect(needsConfirmation('NORMAL', 7, samples)).toBe(true);
  });

  it('keeps adapting after many measures: the newest keep a weight', () => {
    let samples = measured(...Array.from({ length: 50 }, () => ['EASY', 6, 1000] as [string, number, number]));
    expect(samples[sampleKey('EASY', 6)].count).toBe(MAX_SAMPLES);
    for (let i = 0; i < 20; i++) samples = addSample(samples, 'EASY', 6, 3000);
    expect(samples[sampleKey('EASY', 6)].avgMs).toBeGreaterThan(2000);
  });

  it('ignores a time that is not one', () => {
    expect(addSample({}, 'EASY', 6, NaN)).toEqual({});
    expect(addSample({}, 'EASY', 6, -5)).toEqual({});
  });
});
