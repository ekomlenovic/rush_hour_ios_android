// Reads and writes data/campaignPack.ts (one compact level per line, see data/levelCodec.ts)
import fs from 'fs';
import path from 'path';

export const PACK_PATH = path.join(__dirname, '../../data/campaignPack.ts');

export function writePack(codes: string[]): void {
  const lines = codes.map((code, i) => `  /* ${i + 1} */ '${code}',`);
  fs.writeFileSync(PACK_PATH,
    `// Campaign levels in the compact format of data/levelCodec.ts, level id = position in the list.\n` +
    `// Generated by scripts/campaign/build.ts: never edit, reorder or remove a level, only append at the end.\n` +
    `export const CAMPAIGN_PACK: readonly string[] = [\n${lines.join('\n')}\n];\n`);
}
