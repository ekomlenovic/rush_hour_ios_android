import Fastify, { LogController, type FastifyInstance, type FastifyRequest } from 'fastify';
import rateLimit from '@fastify/rate-limit';
import websocket from '@fastify/websocket';
import type { Config } from './config';
import { getSetting, setSetting, type Database } from './db';
import { Challenges, type ChallengeRow } from './challenges';
import type { PuzzleGenerator } from './generation';
import { applyMoves, type MoveRecord } from './core';
import { cleanPseudo, pseudoKey, PSEUDO_MAX } from './pseudo';
import { rankDay, rankPeriod, type GameResult, type GameStatus, type Verdict } from './leaderboard';
import { analyzeGame, type Flag } from './cheat';
import { loadSettings, resetSettings, SettingsError, updateSettings } from './settings';
import { deletePage } from './deletePage';
import { newInviteCode, newRecoveryCode, newToken, normalizeRecoveryCode, secretEquals, sha256 } from './secrets';
import { addDays, isValidDate, localDate, periodBounds } from './time';
import { AUTH_TIMEOUT_MS, DUEL_METRICS, Duels, type ServerMessage } from './duel';
import { DuelStore, rankDuels } from './duelStore';
import { PuzzlePool } from './puzzlePool';

/** Version of this API: the app refuses a server it does not know how to talk to */
export const API_VERSION = 1;
/** Oldest app that can use this server: the version of the app with the multiplayer mode, raised when the API breaks */
export const MIN_APP_VERSION = '1.1.6';
/** A game log longer than this is refused (the hardest puzzles take about 80 moves) */
export const MAX_MOVES = 1000;
/** What this server can do beyond the daily challenge: the app hides what an older server lacks */
/** 'ranking_range': rankings between two dates chosen by the player (period=range&from=…&to=…) */
export const FEATURES = ['duel', 'ranking_range'];
/** A WebSocket that does not answer a ping in this time is closed (phone gone, network lost) */
const PING_INTERVAL_MS = 25_000;
/** Open duel WebSockets from one address at most */
export const MAX_SOCKETS_PER_IP = 10;

export interface AppDeps {
  config: Config;
  db: Database;
  generator: PuzzleGenerator;
  /** Fills the pool of duel puzzles (a worker of its own); the generator by default */
  poolGenerator?: PuzzleGenerator;
  now?: () => number;
  logger?: boolean | object;
  /** Limits of the duel WebSockets, smaller in tests */
  duelLimits?: { authTimeoutMs?: number; socketsPerIp?: number };
}

interface Player { id: number; pseudo: string; created_at: number; is_admin: number; banned: number }

interface AttemptRow {
  id: number;
  player_id: number;
  date: string;
  status: 'playing' | 'won' | 'abandoned';
  started_at: number;
  finished_at: number | null;
  move_count: number | null;
  server_ms: number | null;
  client_ms: number | null;
  background_ms: number | null;
  moves_json: string | null;
  flags_json: string | null;
  verdict: 'cheater' | 'cleared' | null;
}

declare module 'fastify' {
  interface FastifyRequest { player: Player }
}

class ApiError extends Error {
  constructor(readonly status: number, readonly code: string, readonly extra: object = {}) {
    super(code);
  }
}

/** The query of a ranking: a period around a date (today by default), or two dates for 'range' */
type RankingQuery<P extends string> = { period?: P; date?: string; from?: string; to?: string };

const rankingQuerySchema = (periods: string[]) => ({
  type: 'object',
  properties: {
    period: { type: 'string', enum: periods },
    date: { type: 'string', maxLength: 10 },
    from: { type: 'string', maxLength: 10 },
    to: { type: 'string', maxLength: 10 },
  },
});

/**
 * The invite code: the one generated by the admin in the app (#50), else INVITE_CODE,
 * else one generated at the first start and kept in the database
 */
export function inviteCode(db: Database, config: Config): { code: string; generated: boolean } {
  const stored = getSetting(db, 'invite_code');
  if (stored) return { code: stored, generated: false };
  if (config.inviteCode) return { code: config.inviteCode, generated: false };
  const code = newInviteCode();
  setSetting(db, 'invite_code', code);
  return { code, generated: true };
}

export function buildApp(deps: AppDeps) {
  const { config, db, generator, now = Date.now, logger = false } = deps;
  const app: FastifyInstance = Fastify({
    logger: logger === true ? { redact: ['req.headers.authorization'] } : logger,
    trustProxy: config.trustProxy,
    bodyLimit: 64 * 1024,
    // No log line per request: the server keeps no IP addresses (errors are still logged)
    logController: new LogController({ disableRequestLogging: true }),
  });
  const settings = () => loadSettings(db, config);
  const challenges = new Challenges(db, config, generator, now, app.log, settings);
  const invite = inviteCode(db, config);
  if (invite.generated) app.log.info({ inviteCode: invite.code }, 'invite code generated: share it with your friends');

  app.decorateRequest('player', null as unknown as Player);


  app.setErrorHandler((error: Error & { statusCode?: number; validation?: unknown }, request, reply) => {
    if (error instanceof ApiError) return reply.status(error.status).send({ error: error.code, ...error.extra });
    if (error.validation) return reply.status(400).send({ error: 'invalid_request' });
    if (error.statusCode === 429) return reply.status(429).send({ error: 'rate_limited' });
    if (error.statusCode && error.statusCode < 500) return reply.status(error.statusCode).send({ error: 'invalid_request' });
    request.log.error({ err: error }, 'request failed');
    return reply.status(500).send({ error: 'internal' });
  });
  app.setNotFoundHandler((_, reply) => reply.status(404).send({ error: 'not_found' }));

  // ── Players ────────────────────────────────────────────────────────────────

  const PLAYER_FIELDS = 'id, pseudo, created_at, is_admin, banned';
  const findByToken = db.prepare(`SELECT ${PLAYER_FIELDS} FROM players WHERE token_hash = ?`);

  async function authenticate(request: FastifyRequest) {
    const header = request.headers.authorization ?? '';
    const token = header.startsWith('Bearer ') ? header.slice(7).trim() : '';
    const player = token ? findByToken.get(sha256(token)) as Player | undefined : undefined;
    if (!player) throw new ApiError(401, 'unauthorized');
    // Excluded by the admin
    if (player.banned) throw new ApiError(403, 'banned');
    request.player = player;
  }

  async function requireAdmin(request: FastifyRequest) {
    if (!request.player.is_admin) throw new ApiError(403, 'forbidden');
  }

  function pseudoOrThrow(input: unknown): string {
    const pseudo = cleanPseudo(input);
    if (!pseudo) throw new ApiError(400, 'invalid_pseudo');
    return pseudo;
  }

  const isPseudoTaken = (pseudo: string, exceptId = 0) =>
    !!db.prepare('SELECT 1 FROM players WHERE pseudo_key = ? AND id != ?').get(pseudoKey(pseudo), exceptId);

  const publicPlayer = (p: Player) => ({ id: p.id, pseudo: p.pseudo, createdAt: p.created_at, isAdmin: !!p.is_admin });

  const playerById = (id: number) => db.prepare(`SELECT ${PLAYER_FIELDS} FROM players WHERE id = ?`).get(id) as Player | undefined;

  // ── Duels ──────────────────────────────────────────────────────────────────

  const duelStore = new DuelStore(db, config.timeZone);
  // How many are kept ready ahead: the settings of the admin
  const puzzles = new PuzzlePool({ db, generator, fillGenerator: deps.poolGenerator, log: app.log, now, sizes: () => settings().duelPool });
  const duels = new Duels({
    puzzles, now, log: app.log,
    save: (record) => duelStore.save(record),
    authenticate: (token) => {
      const player = token ? findByToken.get(sha256(token)) as Player | undefined : undefined;
      if (!player) return null;
      return player.banned ? 'banned' : { id: player.id, pseudo: player.pseudo };
    },
  });
  const duelLimits = { authTimeoutMs: AUTH_TIMEOUT_MS, socketsPerIp: MAX_SOCKETS_PER_IP, ...deps.duelLimits };
  /** Open WebSockets by address */
  const socketsByIp = new Map<string, number>();
  const duelSweep = setInterval(() => duels.sweep(), 5000);
  duelSweep.unref();
  app.register(websocket, { options: { maxPayload: 4096 } });

  // ── Games ──────────────────────────────────────────────────────────────────

  const getAttempt = (playerId: number, date: string) =>
    db.prepare('SELECT * FROM attempts WHERE player_id = ? AND date = ?').get(playerId, date) as AttemptRow | undefined;

  /** A game still 'playing' after its deadline is unfinished */
  const statusOf = (a: AttemptRow): GameStatus =>
    a.status === 'playing' && now() > challenges.deadline(a.date) ? 'unfinished' : a.status;

  const flagsOf = (a: AttemptRow): Flag[] => (a.flags_json ? JSON.parse(a.flags_json) as Flag[] : []);

  /** 🤡 when the admin confirmed it, ⚠️ when a signal raised a suspicion the admin did not lift */
  function verdictOf(a: AttemptRow): Verdict {
    if (a.verdict === 'cheater') return 'cheater';
    if (a.verdict === 'cleared' || a.status !== 'won') return null;
    return flagsOf(a).length > 0 ? 'suspect' : null;
  }

  function resultsOf(from: string, to: string): GameResult[] {
    // Players excluded by the admin are out of the rankings
    const rows = db.prepare(`
      SELECT a.*, p.pseudo FROM attempts a JOIN players p ON p.id = a.player_id
      WHERE a.date BETWEEN ? AND ? AND p.banned = 0 ORDER BY a.date
    `).all(from, to) as unknown as (AttemptRow & { pseudo: string })[];
    return rows.map(a => {
      const status = statusOf(a);
      const verdict = verdictOf(a);
      return {
        playerId: a.player_id, pseudo: a.pseudo, date: a.date, status,
        moves: status === 'won' ? a.move_count : null,
        timeMs: status === 'won' ? a.server_ms : null,
        attemptId: a.id,
        verdict,
        reasons: verdict === 'suspect' ? flagsOf(a) : [],
      };
    });
  }

  /** The days of a ranking: the day, week or month of a date, or the days between two dates (in any order) */
  function rankingSpan(query: RankingQuery<'day' | 'week' | 'month' | 'range'> & { period: 'day' | 'week' | 'month' | 'range' }, today = challenges.currentDate()) {
    if (query.period === 'range') {
      const { from, to } = query;
      if (!from || !to || !isValidDate(from) || !isValidDate(to)) throw new ApiError(400, 'invalid_request');
      return from <= to ? { from, to } : { from: to, to: from };
    }
    const date = query.date ?? today;
    if (!isValidDate(date)) throw new ApiError(400, 'invalid_request');
    return periodBounds(query.period, date);
  }

  const dayRanking = (date: string) => rankDay(resultsOf(date, date));

  /** The puzzle as sent to a player: its optimum stays hidden until the game is over */
  const puzzleFor = (row: ChallengeRow) => ({ ...challenges.level(row), minMoves: 0 });

  function myGame(a: AttemptRow | undefined, row: ChallengeRow | undefined) {
    if (!a) return null;
    const status = statusOf(a);
    const over = status !== 'playing';
    return {
      status,
      startedAt: a.started_at,
      deadline: challenges.deadline(a.date),
      moves: status === 'won' ? a.move_count : null,
      timeMs: status === 'won' ? a.server_ms : null,
      minMoves: over && row ? row.min_moves : null,
    };
  }

  // ── Routes ─────────────────────────────────────────────────────────────────

  app.register(async (api) => {
    await api.register(rateLimit, { max: 120, timeWindow: '1 minute' });
    const strict = { config: { rateLimit: { max: 10, timeWindow: '15 minutes' } } };

    api.get('/info', async () => ({
      name: settings().serverName,
      apiVersion: API_VERSION,
      minAppVersion: MIN_APP_VERSION,
      features: FEATURES,
    }));

    // Duels in real time: one WebSocket per player, who says who they are in the first message
    api.get('/duel', { websocket: true }, (socket, request) => {
      // A few phones behind one address (a home, a school) at most
      const ip = request.ip;
      const open = (socketsByIp.get(ip) ?? 0) + 1;
      if (open > duelLimits.socketsPerIp) return socket.close(4029, 'rate_limited');
      socketsByIp.set(ip, open);

      let alive = true;
      const connection = duels.connect({
        send: (message: ServerMessage) => {
          if (socket.readyState === socket.OPEN) socket.send(JSON.stringify(message));
        },
        close: (code, reason) => socket.close(code, reason),
      });
      // A connection that never says who it is goes away
      const authTimer = setTimeout(() => {
        if (!connection.authenticated()) socket.close(4001, 'unauthorized');
      }, duelLimits.authTimeoutMs);
      const ping = setInterval(() => {
        if (!alive) return socket.terminate();
        alive = false;
        socket.ping();
      }, PING_INTERVAL_MS);
      socket.on('pong', () => { alive = true; });
      socket.on('message', (data, isBinary) => {
        if (!isBinary) connection.onMessage(data.toString());
      });
      socket.on('close', () => {
        clearTimeout(authTimer);
        clearInterval(ping);
        const left = (socketsByIp.get(ip) ?? 1) - 1;
        if (left > 0) socketsByIp.set(ip, left);
        else socketsByIp.delete(ip);
        connection.onClose();
      });
    });

    api.post<{ Body: { inviteCode: string; pseudo: string } }>('/join', {
      ...strict,
      schema: {
        body: {
          type: 'object', required: ['inviteCode', 'pseudo'],
          properties: { inviteCode: { type: 'string', maxLength: 200 }, pseudo: { type: 'string', maxLength: PSEUDO_MAX * 4 } },
        },
      },
    }, async (request, reply) => {
      if (!settings().joinOpen) throw new ApiError(403, 'join_closed');
      if (!secretEquals(request.body.inviteCode.trim(), inviteCode(db, config).code)) throw new ApiError(403, 'invalid_invite');
      const pseudo = pseudoOrThrow(request.body.pseudo);
      if (isPseudoTaken(pseudo)) throw new ApiError(409, 'pseudo_taken');
      const token = newToken();
      const recoveryCode = newRecoveryCode();
      const result = db.prepare('INSERT INTO players (pseudo, pseudo_key, token_hash, recovery_hash, created_at) VALUES (?, ?, ?, ?, ?)')
        .run(pseudo, pseudoKey(pseudo), sha256(token), sha256(normalizeRecoveryCode(recoveryCode)), now());
      const player = playerById(Number(result.lastInsertRowid))!;
      return reply.status(201).send({ token, recoveryCode, player: publicPlayer(player), server: { name: settings().serverName } });
    });

    api.post<{ Body: { recoveryCode: string } }>('/recover', {
      ...strict,
      schema: {
        body: { type: 'object', required: ['recoveryCode'], properties: { recoveryCode: { type: 'string', maxLength: 100 } } },
      },
    }, async (request) => {
      const hash = sha256(normalizeRecoveryCode(request.body.recoveryCode));
      const player = db.prepare(`SELECT ${PLAYER_FIELDS} FROM players WHERE recovery_hash = ?`).get(hash) as Player | undefined;
      if (!player) throw new ApiError(403, 'invalid_recovery_code');
      if (player.banned) throw new ApiError(403, 'banned');
      // A new token: the previous phone is signed out (its duel connection too)
      const token = newToken();
      db.prepare('UPDATE players SET token_hash = ? WHERE id = ?').run(sha256(token), player.id);
      duels.kick(player.id, 'signed_out');
      return { token, player: publicPlayer(player), server: { name: settings().serverName } };
    });

    // Everything else needs a player
    api.register(async (auth) => {
      auth.addHook('onRequest', authenticate);

      auth.get('/me', async (request) => publicPlayer(request.player));

      auth.patch<{ Body: { pseudo: string } }>('/me', {
        schema: { body: { type: 'object', required: ['pseudo'], properties: { pseudo: { type: 'string', maxLength: PSEUDO_MAX * 4 } } } },
      }, async (request) => {
        const pseudo = pseudoOrThrow(request.body.pseudo);
        if (isPseudoTaken(pseudo, request.player.id)) throw new ApiError(409, 'pseudo_taken');
        db.prepare('UPDATE players SET pseudo = ?, pseudo_key = ? WHERE id = ?').run(pseudo, pseudoKey(pseudo), request.player.id);
        return publicPlayer({ ...request.player, pseudo });
      });

      // Every member can invite a friend, unless the admin keeps invitations to themselves
      auth.get('/invite', async (request) => {
        if (settings().invitesAdminOnly && !request.player.is_admin) throw new ApiError(403, 'invites_admin_only');
        return { inviteCode: inviteCode(db, config).code };
      });

      auth.post('/me/recovery', async (request) => {
        const recoveryCode = newRecoveryCode();
        db.prepare('UPDATE players SET recovery_hash = ? WHERE id = ?').run(sha256(normalizeRecoveryCode(recoveryCode)), request.player.id);
        return { recoveryCode };
      });

      auth.delete('/me', async (request, reply) => {
        // Games and duels go with the player (ON DELETE CASCADE)
        duels.kick(request.player.id, 'deleted');
        db.prepare('DELETE FROM players WHERE id = ?').run(request.player.id);
        return reply.status(204).send();
      });

      // The duels of the server: open ones to join, and the ones being played
      auth.get('/duels', async (request) => ({
        duels: duels.list(request.player.id),
        // Puzzles ready by difficulty: a duel of a difficulty with none waits for its puzzle
        ready: puzzles.counts(),
        // What can decide the winner of a new duel (absent on older servers: the time)
        metrics: DUEL_METRICS,
      }));

      // Duel rankings: wins, then fewer losses
      auth.get<{ Querystring: RankingQuery<'day' | 'week' | 'month' | 'all' | 'range'> }>('/duels/leaderboard', {
        schema: { querystring: rankingQuerySchema(['day', 'week', 'month', 'all', 'range']) },
      }, async (request) => {
        const period = request.query.period ?? 'week';
        // Duels are dated by the day they end (not by the challenge, which lags until its release):
        // on a Monday morning, the week is the new one
        const { from, to } = period === 'all' ? { from: '0000-01-01', to: '9999-12-31' }
          : rankingSpan({ ...request.query, period }, localDate(now(), config.timeZone));
        return { period, from, to, rows: rankDuels(duelStore.stats(from, to)) };
      });

      // My last duels, and my score against each opponent
      auth.get('/duels/history', async (request) => ({
        duels: duelStore.history(request.player.id),
        records: duelStore.records(request.player.id),
      }));

      // A duel with the moves of both players: for its players (and the admin)
      auth.get<{ Params: { id: string } }>('/duels/:id', {
        schema: { params: { type: 'object', properties: { id: { type: 'integer', minimum: 1 } } } },
      }, async (request) => {
        const replay = duelStore.replay(Number(request.params.id));
        if (!replay) throw new ApiError(404, 'replay_unavailable');
        if (!request.player.is_admin && !replay.players.some(p => p.id === request.player.id)) throw new ApiError(403, 'forbidden');
        if (!replay.hasReplay) throw new ApiError(410, 'replay_expired');
        const { hasReplay: _, ...rest } = replay;
        return rest;
      });

      auth.get('/challenge/today', async (request) => {
        const date = challenges.currentDate();
        const row = challenges.get(date);
        // Not generated yet (server just started): on its way, the app shows "preparing"
        if (!row) challenges.ensure(date).catch(err => request.log.error({ err }, 'challenge generation failed'));
        const mine = getAttempt(request.player.id, date);
        // A game of the previous challenge that can still be finished (grace period)
        const previous = getAttempt(request.player.id, addDays(date, -1));
        return {
          date,
          number: challenges.number(date),
          status: row ? 'ready' : 'preparing',
          releasedAt: challenges.releaseAt(date),
          closesAt: challenges.closesAt(date),
          serverNow: now(),
          me: myGame(mine, row),
          pending: previous && statusOf(previous) === 'playing'
            ? { date: previous.date, deadline: challenges.deadline(previous.date) } : null,
          results: dayRanking(date),
        };
      });

      auth.post<{ Body: { date?: string } }>('/challenge/start', {
        schema: { body: { type: ['object', 'null'], properties: { date: { type: 'string', maxLength: 10 } } } },
      }, async (request) => {
        const current = challenges.currentDate();
        const date = request.body?.date ?? current;
        if (!isValidDate(date)) throw new ApiError(400, 'invalid_request');

        const existing = getAttempt(request.player.id, date);
        if (existing && statusOf(existing) !== 'playing') throw new ApiError(409, 'already_finished');
        // Only the current challenge can be started; an earlier one only resumed
        if (!existing && date !== current) throw new ApiError(409, 'challenge_closed');

        const row = challenges.get(date) ?? (date === current ? await challenges.ensure(date) : undefined);
        if (!row) throw new ApiError(503, 'preparing');

        let attempt = existing;
        if (!attempt) {
          db.prepare("INSERT OR IGNORE INTO attempts (player_id, date, status, started_at) VALUES (?, ?, 'playing', ?)")
            .run(request.player.id, date, now());
          attempt = getAttempt(request.player.id, date)!;
        }
        return {
          date,
          number: challenges.number(date),
          startedAt: attempt.started_at,
          deadline: challenges.deadline(date),
          serverNow: now(),
          level: puzzleFor(row),
        };
      });

      auth.post<{ Body: { date: string; moves: MoveRecord[]; clientMs?: number; backgroundMs?: number } }>('/challenge/submit', {
        schema: {
          body: {
            type: 'object', required: ['date', 'moves'],
            properties: {
              date: { type: 'string', maxLength: 10 },
              moves: {
                type: 'array', maxItems: MAX_MOVES,
                items: {
                  type: 'object', required: ['vehicleId', 'delta', 't'],
                  properties: { vehicleId: { type: 'string', maxLength: 32 }, delta: { type: 'integer' }, t: { type: 'number' } },
                },
              },
              clientMs: { type: 'number', minimum: 0 },
              backgroundMs: { type: 'number', minimum: 0 },
            },
          },
        },
      }, async (request) => {
        const { date, moves, clientMs, backgroundMs } = request.body;
        const attempt = getAttempt(request.player.id, date);
        if (!attempt) throw new ApiError(404, 'no_game');
        const status = statusOf(attempt);
        if (status === 'unfinished') throw new ApiError(409, 'too_late');
        if (status !== 'playing') throw new ApiError(409, 'already_finished');

        const row = challenges.get(date)!;
        const replay = applyMoves(challenges.level(row), moves);
        if (!replay.ok) throw new ApiError(400, 'invalid_moves', { reason: replay.error, index: replay.index });
        if (!replay.won) throw new ApiError(400, 'not_won');

        const finishedAt = now();
        const serverMs = finishedAt - attempt.started_at;
        const moveLog = moves.map(({ vehicleId, delta, t }) => ({ vehicleId, delta, t }));
        const client = clientMs === undefined ? null : Math.round(clientMs);
        const flags = analyzeGame({ moves: moveLog, minMoves: row.min_moves, serverMs, clientMs: client }, settings().thresholds);
        db.prepare(`
          UPDATE attempts SET status = 'won', finished_at = ?, move_count = ?, server_ms = ?, client_ms = ?, background_ms = ?, moves_json = ?, flags_json = ?
          WHERE id = ? AND status = 'playing'
        `).run(finishedAt, replay.moveCount, serverMs, client, backgroundMs === undefined ? null : Math.round(backgroundMs),
          JSON.stringify(moveLog), flags.length ? JSON.stringify(flags) : null, attempt.id);

        const mine = dayRanking(date).find(r => r.playerId === request.player.id)!;
        return {
          status: 'won', moves: replay.moveCount, timeMs: serverMs,
          minMoves: row.min_moves, rank: mine.rank, points: mine.points, verdict: mine.verdict,
        };
      });

      auth.post<{ Body: { date: string } }>('/challenge/abandon', {
        schema: { body: { type: 'object', required: ['date'], properties: { date: { type: 'string', maxLength: 10 } } } },
      }, async (request) => {
        const attempt = getAttempt(request.player.id, request.body.date);
        if (!attempt) throw new ApiError(404, 'no_game');
        if (attempt.status !== 'playing') throw new ApiError(409, 'already_finished');
        db.prepare("UPDATE attempts SET status = 'abandoned', finished_at = ? WHERE id = ?").run(now(), attempt.id);
        return { status: 'abandoned', minMoves: challenges.get(attempt.date)?.min_moves ?? null };
      });

      auth.get<{ Querystring: RankingQuery<'day' | 'week' | 'month' | 'range'> }>('/leaderboard', {
        schema: { querystring: rankingQuerySchema(['day', 'week', 'month', 'range']) },
      }, async (request) => {
        const period = request.query.period ?? 'day';
        const { from, to } = rankingSpan({ ...request.query, period });
        const results = resultsOf(from, to);
        return {
          period, from, to,
          rows: period === 'day' ? rankDay(results) : rankPeriod(results),
        };
      });

      // ── Replays ────────────────────────────────────────────────────────────

      auth.get<{ Params: { id: string } }>('/replay/:id', {
        schema: { params: { type: 'object', properties: { id: { type: 'integer', minimum: 1 } } } },
      }, async (request) => {
        const attempt = db.prepare('SELECT a.*, p.pseudo FROM attempts a JOIN players p ON p.id = a.player_id WHERE a.id = ?')
          .get(Number(request.params.id)) as (AttemptRow & { pseudo: string }) | undefined;
        if (!attempt || attempt.status !== 'won') throw new ApiError(404, 'replay_unavailable');
        // Never a spoiler: only once my own game of that day is over, or the challenge is closed
        const mine = getAttempt(request.player.id, attempt.date);
        const allowed = !!request.player.is_admin
          || now() >= challenges.closesAt(attempt.date)
          || (!!mine && statusOf(mine) !== 'playing');
        if (!allowed) throw new ApiError(403, 'replay_locked');
        if (!attempt.moves_json) throw new ApiError(410, 'replay_expired');
        const row = challenges.get(attempt.date)!;
        return {
          attemptId: attempt.id,
          playerId: attempt.player_id,
          pseudo: attempt.pseudo,
          date: attempt.date,
          number: challenges.number(attempt.date),
          level: challenges.level(row),
          moves: JSON.parse(attempt.moves_json) as MoveRecord[],
          timeMs: attempt.server_ms,
          verdict: verdictOf(attempt),
          reasons: verdictOf(attempt) === 'suspect' ? flagsOf(attempt) : [],
        };
      });

      // ── Moderation ─────────────────────────────────────────────────────────

      auth.post<{ Body: { playerId: number; reason?: string } }>('/reports', {
        schema: {
          body: {
            type: 'object', required: ['playerId'],
            properties: { playerId: { type: 'integer', minimum: 1 }, reason: { type: 'string', maxLength: 200 } },
          },
        },
      }, async (request, reply) => {
        const { playerId, reason = '' } = request.body;
        if (playerId === request.player.id) throw new ApiError(400, 'invalid_request');
        if (!playerById(playerId)) throw new ApiError(404, 'not_found');
        // One report per player and per reporter: reporting again updates the reason
        db.prepare(`
          INSERT INTO reports (reporter_id, player_id, reason, created_at) VALUES (?, ?, ?, ?)
          ON CONFLICT(reporter_id, player_id) DO UPDATE SET reason = excluded.reason, created_at = excluded.created_at
        `).run(request.player.id, playerId, reason.trim(), now());
        return reply.status(204).send();
      });

      // ── Admin ──────────────────────────────────────────────────────────────

      // The creator of the server becomes admin on their player account with ADMIN_TOKEN
      auth.post<{ Body: { adminToken: string } }>('/admin/claim', {
        ...strict,
        schema: { body: { type: 'object', required: ['adminToken'], properties: { adminToken: { type: 'string', maxLength: 500 } } } },
      }, async (request) => {
        if (!secretEquals(request.body.adminToken.trim(), config.adminToken)) throw new ApiError(403, 'invalid_admin_token');
        db.prepare('UPDATE players SET is_admin = 1 WHERE id = ?').run(request.player.id);
        return publicPlayer({ ...request.player, is_admin: 1 });
      });

      auth.register(async (admin) => {
        admin.addHook('onRequest', requireAdmin);

        // Games to review: the suspect ones first, with all their signals
        admin.get<{ Querystring: { filter?: 'suspects' | 'all' } }>('/admin/games', {
          schema: { querystring: { type: 'object', properties: { filter: { type: 'string', enum: ['suspects', 'all'] } } } },
        }, async (request) => {
          const suspectsOnly = (request.query.filter ?? 'suspects') === 'suspects';
          const rows = db.prepare(`
            SELECT a.*, p.pseudo FROM attempts a JOIN players p ON p.id = a.player_id
            WHERE a.status = 'won' ${suspectsOnly ? "AND (a.flags_json IS NOT NULL OR a.verdict IS NOT NULL)" : ''}
            ORDER BY a.finished_at DESC LIMIT 100
          `).all() as unknown as (AttemptRow & { pseudo: string })[];
          return {
            games: rows.map(a => ({
              attemptId: a.id, playerId: a.player_id, pseudo: a.pseudo, date: a.date,
              moves: a.move_count, minMoves: challenges.get(a.date)?.min_moves ?? null,
              timeMs: a.server_ms, clientMs: a.client_ms, backgroundMs: a.background_ms,
              flags: flagsOf(a), adminVerdict: a.verdict, verdict: verdictOf(a), hasReplay: !!a.moves_json,
            })),
          };
        });

        admin.post<{ Params: { id: string }; Body: { verdict: 'cheater' | 'cleared' | null } }>('/admin/games/:id/verdict', {
          schema: {
            params: { type: 'object', properties: { id: { type: 'integer', minimum: 1 } } },
            body: { type: 'object', required: ['verdict'], properties: { verdict: { type: ['string', 'null'], enum: ['cheater', 'cleared', null] } } },
          },
        }, async (request) => {
          const result = db.prepare("UPDATE attempts SET verdict = ? WHERE id = ? AND status = 'won'")
            .run(request.body.verdict, Number(request.params.id));
          if (!result.changes) throw new ApiError(404, 'not_found');
          return { verdict: request.body.verdict };
        });

        admin.get('/admin/players', async () => {
          const rows = db.prepare(`
            SELECT p.id, p.pseudo, p.created_at, p.is_admin, p.banned,
              (SELECT COUNT(*) FROM attempts a WHERE a.player_id = p.id) AS games,
              (SELECT COUNT(*) FROM reports r WHERE r.player_id = p.id) AS reports
            FROM players p ORDER BY p.pseudo_key
          `).all() as unknown as (Player & { games: number; reports: number })[];
          return {
            players: rows.map(p => ({ ...publicPlayer(p), banned: !!p.banned, games: p.games, reports: p.reports })),
          };
        });

        admin.patch<{ Params: { id: string }; Body: { pseudo?: string; banned?: boolean } }>('/admin/players/:id', {
          schema: {
            params: { type: 'object', properties: { id: { type: 'integer', minimum: 1 } } },
            body: { type: 'object', properties: { pseudo: { type: 'string', maxLength: PSEUDO_MAX * 4 }, banned: { type: 'boolean' } } },
          },
        }, async (request) => {
          const target = playerById(Number(request.params.id));
          if (!target) throw new ApiError(404, 'not_found');
          if (request.body.pseudo !== undefined) {
            const pseudo = pseudoOrThrow(request.body.pseudo);
            if (isPseudoTaken(pseudo, target.id)) throw new ApiError(409, 'pseudo_taken');
            db.prepare('UPDATE players SET pseudo = ?, pseudo_key = ? WHERE id = ?').run(pseudo, pseudoKey(pseudo), target.id);
          }
          if (request.body.banned !== undefined) {
            // An admin is never excluded (not even by mistake, by themselves)
            if (target.is_admin && request.body.banned) throw new ApiError(400, 'cannot_ban_admin');
            db.prepare('UPDATE players SET banned = ? WHERE id = ?').run(request.body.banned ? 1 : 0, target.id);
            if (request.body.banned) duels.kick(target.id, 'banned');
          }
          return { ...publicPlayer(playerById(target.id)!), banned: !!playerById(target.id)!.banned };
        });

        // A player who lost their recovery code: a new one, to give them (the old one stops working)
        admin.post<{ Params: { id: string } }>('/admin/players/:id/transfer', {
          schema: { params: { type: 'object', properties: { id: { type: 'integer', minimum: 1 } } } },
        }, async (request) => {
          const target = playerById(Number(request.params.id));
          if (!target) throw new ApiError(404, 'not_found');
          const recoveryCode = newRecoveryCode();
          db.prepare('UPDATE players SET recovery_hash = ? WHERE id = ?').run(sha256(normalizeRecoveryCode(recoveryCode)), target.id);
          return { recoveryCode };
        });

        // Delete a player and all their games, as they could themselves (DELETE /me): an admin is never deleted from here
        admin.delete<{ Params: { id: string } }>('/admin/players/:id', {
          schema: { params: { type: 'object', properties: { id: { type: 'integer', minimum: 1 } } } },
        }, async (request, reply) => {
          const target = playerById(Number(request.params.id));
          if (!target) throw new ApiError(404, 'not_found');
          if (target.is_admin) throw new ApiError(400, 'cannot_delete_admin');
          duels.kick(target.id, 'deleted');
          db.prepare('DELETE FROM players WHERE id = ?').run(target.id);
          return reply.status(204).send();
        });

        admin.get('/admin/reports', async () => {
          const rows = db.prepare(`
            SELECT r.id, r.reason, r.created_at, r.player_id, p.pseudo, r.reporter_id, q.pseudo AS reporter
            FROM reports r JOIN players p ON p.id = r.player_id JOIN players q ON q.id = r.reporter_id
            ORDER BY r.created_at DESC
          `).all() as unknown as { id: number; reason: string; created_at: number; player_id: number; pseudo: string; reporter_id: number; reporter: string }[];
          return {
            reports: rows.map(r => ({
              id: r.id, reason: r.reason, createdAt: r.created_at,
              player: { id: r.player_id, pseudo: r.pseudo }, reporter: { id: r.reporter_id, pseudo: r.reporter },
            })),
          };
        });

        admin.delete<{ Params: { id: string } }>('/admin/reports/:id', {
          schema: { params: { type: 'object', properties: { id: { type: 'integer', minimum: 1 } } } },
        }, async (request, reply) => {
          db.prepare('DELETE FROM reports WHERE id = ?').run(Number(request.params.id));
          return reply.status(204).send();
        });

        // Back to zero: the games of the daily challenges and/or the duels between two days, of some players or all
        admin.post<{ Body: { from?: string | null; to?: string | null; playerIds?: number[]; challenges?: boolean; duels?: boolean; dryRun?: boolean } }>('/admin/reset', {
          schema: {
            body: {
              type: 'object',
              properties: {
                from: { type: ['string', 'null'], maxLength: 10 },
                to: { type: ['string', 'null'], maxLength: 10 },
                playerIds: { type: 'array', maxItems: 1000, items: { type: 'integer', minimum: 1 } },
                challenges: { type: 'boolean' },
                duels: { type: 'boolean' },
                dryRun: { type: 'boolean' },
              },
            },
          },
        }, async (request) => {
          const { from, to, playerIds = [], challenges: games = false, duels: withDuels = false, dryRun = false } = request.body;
          if ((from && !isValidDate(from)) || (to && !isValidDate(to)) || (from && to && from > to)) throw new ApiError(400, 'invalid_request');
          const range = [from || '0000-01-01', to || '9999-12-31'];
          const some = playerIds.length > 0;
          const marks = playerIds.map(() => '?').join(', ');
          const count = { challenges: 0, duels: 0 };
          const run = (table: string, where: string, args: (string | number)[]) => {
            if (dryRun) return Number((db.prepare(`SELECT COUNT(*) AS n FROM ${table} WHERE ${where}`).get(...args) as { n: number }).n);
            return Number(db.prepare(`DELETE FROM ${table} WHERE ${where}`).run(...args).changes);
          };
          db.exec('BEGIN');
          try {
            if (games) {
              count.challenges = run('attempts', `date BETWEEN ? AND ?${some ? ` AND player_id IN (${marks})` : ''}`, [...range, ...playerIds]);
            }
            if (withDuels) {
              count.duels = run('duels', `date BETWEEN ? AND ?${some ? ` AND (player1_id IN (${marks}) OR player2_id IN (${marks}))` : ''}`,
                [...range, ...playerIds, ...playerIds]);
            }
            db.exec('COMMIT');
          } catch (e) {
            db.exec('ROLLBACK');
            throw e;
          }
          if (!dryRun) request.log.info({ admin: request.player.id, from, to, players: some ? playerIds : 'all', ...count }, 'admin reset');
          return { dryRun, ...count };
        });

        // What the home of the admin panel shows: what is waiting, and a word on each part
        admin.get('/admin/summary', async () => {
          const flagged = db.prepare(`
            SELECT a.* FROM attempts a WHERE a.status = 'won' AND a.flags_json IS NOT NULL AND a.verdict IS NULL
          `).all() as unknown as AttemptRow[];
          const count = (sql: string) => Number((db.prepare(sql).get() as { n: number }).n);
          const pool = puzzles.overview();
          const current = settings();
          return {
            toReview: flagged.filter(a => verdictOf(a) === 'suspect').length,
            reports: count('SELECT COUNT(*) AS n FROM reports'),
            players: count('SELECT COUNT(*) AS n FROM players'),
            banned: count('SELECT COUNT(*) AS n FROM players WHERE banned = 1'),
            joinOpen: current.joinOpen,
            invitesAdminOnly: current.invitesAdminOnly,
            serverName: current.serverName,
            releaseTime: current.releaseTime,
            puzzles: {
              ready: pool.difficulties.reduce((n, d) => n + d.ready, 0),
              size: pool.difficulties.reduce((n, d) => n + d.size, 0),
              working: pool.working,
            },
          };
        });

        // The duel puzzles ready ahead, and the one being generated
        admin.get('/admin/puzzles', async () => puzzles.overview());

        // The daily challenges: the current one and the next ones, ready or not, and where they come from
        admin.get('/admin/challenges', async () => ({ challenges: challenges.overview() }));

        // A leaked invitation: a new code, the old links stop working
        admin.post('/admin/invite', async () => {
          const code = newInviteCode();
          setSetting(db, 'invite_code', code);
          return { inviteCode: code };
        });

        // The changes of release time are the server's business: the app gets when the next challenge comes out
        const settingsView = () => {
          const { releaseChanges: _, ...rest } = settings();
          return { ...rest, timeZone: config.timeZone, nextReleaseAt: challenges.releaseAt(addDays(challenges.currentDate(), 1)) };
        };

        admin.get('/admin/settings', async () => settingsView());

        admin.patch<{ Body: Record<string, unknown> }>('/admin/settings', {
          schema: { body: { type: 'object' } },
        }, async (request) => {
          try {
            updateSettings(db, config, request.body, now());
            // A new difficulty: the puzzles not released yet are generated again right away
            void challenges.tick();
            if ('duelPool' in request.body) puzzles.resized();
            return settingsView();
          } catch (e) {
            if (e instanceof SettingsError) throw new ApiError(400, e.code, { field: e.message });
            throw e;
          }
        });

        // Back to the docker-compose
        admin.post('/admin/settings/reset', async () => {
          try {
            resetSettings(db, config, now());
            void challenges.tick();
            puzzles.resized();
            return settingsView();
          } catch (e) {
            if (e instanceof SettingsError) throw new ApiError(400, e.code, { field: e.message });
            throw e;
          }
        });
      });
    });
  }, { prefix: '/api/v1' });

  // Delete an account from the web (Google Play), with the recovery code
  app.register(deletePage, { db, serverName: () => settings().serverName, onDeleted: playerId => duels.kick(playerId, 'deleted') });

  app.addHook('preClose', async () => {
    clearInterval(duelSweep);
    duels.closeAll();
    puzzles.stop();
  });

  app.addHook('onClose', async () => {
    await challenges.stop();
  });

  return { app, challenges, duels, puzzles };
}


